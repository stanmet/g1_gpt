#!/usr/bin/env python3
"""
Generates src/background/glassfont.data.ts: 1-bit glyphs for drawing text into the G1 bitmap
(the navigation screen). The glasses take a picture, not text, so the picture needs its own font.

Font: Inter (SIL Open Font License 1.1, https://rsms.me/inter/), rendered without anti-aliasing.

Run: python3 scripts/gen-glass-font.py  (needs Pillow and the Inter .otf files)
"""
import base64
import json
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "background", "glassfont.data.ts")
INTER = "/usr/share/fonts/opentype/inter/"

TEXT_CHARS = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "".join(chr(c) for c in range(0xC0, 0x100))
    + "".join(chr(c) for c in range(0x410, 0x450))
    + "Ёё–—«»…·’‘“”№°"
)
BIG_CHARS = "0123456789 ,.:-–мкчинсмkmhin"

FONTS = {
    "text": (INTER + "Inter-SemiBold.otf", 19, TEXT_CHARS),
    "big": (INTER + "Inter-Bold.otf", 34, BIG_CHARS),
}


def glyphs(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    out = {}
    bits = bytearray()
    for ch in sorted(set(chars)):
        advance = round(font.getlength(ch))
        img = Image.new("1", (size * 3, size * 3), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        ox, oy = size, size  # room for negative bearings
        d.text((ox, oy), ch, font=font, fill=1)
        box = img.getbbox()
        if not box:
            out[ch] = [advance, 0, 0, 0, 0, len(bits)]
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        start = len(bits)
        row_bytes = (w + 7) // 8
        px = img.load()
        for y in range(y0, y1):
            row = bytearray(row_bytes)
            for x in range(x0, x1):
                if px[x, y]:
                    i = x - x0
                    row[i // 8] |= 0x80 >> (i % 8)
            bits += row
        # offsets: from the pen position (left) and the top of the line box
        out[ch] = [advance, x0 - ox, y0 - oy, w, h, start]
    return {"ascent": ascent, "descent": descent, "lineHeight": ascent + descent, "glyphs": out, "bits": base64.b64encode(bytes(bits)).decode()}


def main():
    data = {name: glyphs(*spec) for name, spec in FONTS.items()}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/gen-glass-font.py — do not edit. Inter, SIL Open Font License 1.1.\n")
        f.write("/* eslint-disable */\n")
        f.write("export const GLASS_FONTS = ")
        f.write(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
        f.write(" as const\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
